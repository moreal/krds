import { chromium, webkit } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { writeFile } from 'node:fs/promises';
const browser = await (process.env.KRDS_DOCS_INSPECT_BROWSER === 'webkit' ? webkit : chromium).launch();
const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.goto('http://127.0.0.1:49100', { waitUntil: 'networkidle' });
console.log('Initial focus', await page.locator(':focus').evaluateAll(elements => elements.map(element => element.outerHTML.slice(0, 400))));
await page.keyboard.press('Tab');
const before = await page.evaluate(() => ({ active: document.activeElement.outerHTML, ready: document.readyState }));
await page.keyboard.press('Enter');
const after = await page.evaluate(() => ({ active: document.activeElement.outerHTML.slice(0, 500), target: document.getElementById('VPContent')?.outerHTML.slice(0, 400) }));
await page.screenshot({ path: '../../.superpowers/sdd/PLAN/t12-docs-logs/browser/inspect-home.png', fullPage: true });
const axe = await new AxeBuilder({ page }).analyze();
console.log(JSON.stringify({ errors, before, after, violations: axe.violations.map(item => ({ id: item.id, nodes: item.nodes.map(node => ({ target: node.target, html: node.html, summary: node.failureSummary })) })) }));
await page.goto('http://127.0.0.1:49100/components/', { waitUntil: 'networkidle' });
await page.locator('.vp-doc').getByRole('link', { name: 'Badge', exact: true }).click();
await page.screenshot({ path: '../../.superpowers/sdd/PLAN/t12-docs-logs/browser/inspect-badge.png', fullPage: true });
console.log(JSON.stringify({ url: page.url(), errors, headings: await page.locator('h1').allTextContents(), body: (await page.locator('body').innerText()).slice(0, 1600) }));
await browser.close();
